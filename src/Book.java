public class Book {
    private String title;

    /**
     * Constructs a new Book with the specified title.
     *
     * @param String title
     */
    public Book(String title) {
        this.title = title;
    }

    /**
     * Returns the title of the book.
     *
     * @return String
     */
    public String getTitle() {
        return this.title;
    }
}
